import { chromium } from 'playwright-core';
import { mkdirSync } from 'node:fs';
const [url, dir, w = '390', h = '844'] = process.argv.slice(2);
mkdirSync(dir, { recursive: true });
const b = await chromium.launch({ executablePath: process.env.HOME + '/.cache/ms-playwright/chromium-1243/chrome-linux64/chrome' });
const p = await b.newPage({ viewport: { width: +w, height: +h } });
const errs = [], failed = [];
p.on('console', m => m.type() === 'error' && errs.push(m.text()));
p.on('pageerror', e => errs.push('PAGEERROR ' + e.message));
p.on('requestfailed', r => failed.push(r.url() + ' ' + r.failure()?.errorText));
const tab = name => p.getByText(name, { exact: true }).last().click().then(() => p.waitForTimeout(900));
const shot = n => p.screenshot({ path: `${dir}/${w}x${h}-${n}.png` });
const check = async (label, re) => { const t = await p.locator('body').innerText(); console.log(label, re.test(t) ? 'PASS' : 'FAIL'); };

await p.goto(url, { waitUntil: 'networkidle' }); await p.waitForTimeout(1500);
await shot('01-home-empty');
await p.getByText('Log Weight', { exact: true }).first().click(); await p.waitForTimeout(800);
await p.getByLabel('Weight (lb)', { exact: true }).last().fill('182.4');
await p.getByLabel('Note', { exact: true }).last().fill('web launch check');
await p.getByText('Save weigh-in', { exact: true }).click(); await p.waitForTimeout(900);
await check('weight saved', /1 entr/);
await shot('02-weight-saved');
await tab('Log');
await p.getByText('New Routine', { exact: true }).first().click(); await p.waitForTimeout(700);
await p.getByPlaceholder('Routine Name (e.g. Push Day)').fill('Web Launch Check');
await p.locator('textarea').first().fill('Monday\n+Lifting\n-Bench\n135 5,5,5');
await p.getByText('Done', { exact: true }).first().click(); await p.waitForTimeout(900);
await shot('03-log-saved');
for (const t of ['Home', 'Weight', 'Analytics', 'More']) { await tab(t); await shot(`04-${t.toLowerCase()}`); }
console.log('MORE TEXT:\n' + (await p.locator('body').innerText()).slice(0, 1200));
await p.reload({ waitUntil: 'networkidle' }); await p.waitForTimeout(1500);
await shot('05-home-after-reload');
await check('home populated after reload', /182\.4/);
await tab('Weight'); await check('weight persisted', /182\.4/);
await tab('Log'); await check('routine persisted', /Web Launch Check|Bench/);
await shot('06-log-after-reload');
const store = await p.evaluate(() => Object.keys(localStorage));
console.log('localStorage keys', JSON.stringify(store));
console.log('ERRORS', JSON.stringify(errs)); console.log('FAILED', JSON.stringify(failed));
await b.close();
