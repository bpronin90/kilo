// #1655 after-render capture. Fresh local-only browser context at 390x844;
// non-local requests are blocked. Start Expo web on 8098 first (see README).
// Usage: PLAYWRIGHT_MODULE=<path to playwright> node capture.cjs <out dir>
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const out=process.argv[2] || '.';

(async()=>{const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
const page=await context.newPage();
page.setDefaultTimeout(15000);
await page.route('**/*',route=>{const u=new URL(route.request().url());
return ['localhost','127.0.0.1'].includes(u.hostname)?route.continue():route.abort();
});
const shot=async(name,opts={})=>page.screenshot({path:`${out}/${name}.png`,...opts});
await page.goto('http://localhost:8098',{timeout:180000});
await page.getByRole('button',{name:'Skip',exact:true}).click({timeout:120000});
await page.getByRole('tab',{name:'Log',exact:true}).click();
await page.waitForTimeout(500);
await shot('1-log-empty-state',{fullPage:true});
console.log('EMPTY STATE',await page.locator('body').innerText());
await page.mouse.move(195,500);
await page.mouse.wheel(0,450);
await page.waitForTimeout(400);
await shot('1b-log-empty-state-rows');
await page.getByRole('button',{name:'New Routine',exact:true}).click();
await page.waitForTimeout(400);
console.log('PLACEHOLDER',await page.locator('textarea').evaluateAll(ns=>ns.map(n=>n.placeholder)));
await shot('2-editor-placeholder');
await page.getByRole('button',{name:'Workout syntax help'}).click();
await page.waitForTimeout(400);
await shot('3-syntax-help');
console.log('SYNTAX HELP',await page.locator('body').innerText());
await page.getByRole('button',{name:'Close workout syntax help'}).click();
await page.getByRole('button',{name:'Insert example workout note'}).click();
console.log('SEED',await page.locator('textarea').inputValue());
await page.getByRole('button',{name:'Done',exact:true}).click();
await page.waitForTimeout(800);
await shot('4-saved-not-current');
console.log('SAVED',await page.locator('body').innerText());
await page.getByRole('button',{name:/Use Untitled Routine as your current routine/}).click();
await page.waitForTimeout(700);
await shot('5-adopted');
console.log('ADOPTED',await page.locator('body').innerText());
await page.getByRole('tab',{name:'Analytics',exact:true}).click();
await page.waitForTimeout(800);
const horizontal=page.getByText(/Horizontal push/).first();
await horizontal.scrollIntoViewIfNeeded();
await shot('6-training-classified');
console.log('ANALYTICS',await page.locator('body').innerText());
await browser.close()})().catch(e=>{console.error(e);
process.exit(1)});
